"""mypkg というパッケージを表す `__init__.py`。

このファイルが存在することで、`mypkg/` ディレクトリは Python の **package**
として扱われる（厳密には Python 3.3+ では `__init__.py` が無くても
"namespace package" として認識されるが、通常の package は明示的に書く）。

ここに書いたコードは:
- `import mypkg` または `from mypkg import ...` のときに **1 度だけ** 実行される
- 何度 import しても再実行されない（モジュールは sys.modules にキャッシュされる）

主な使い道は次のとおり:
- パッケージのメタ情報（__version__ 等）の公開
- 内部モジュールから「公開 API」だけを引き上げて再エクスポート
- `from mypkg import *` の対象を `__all__` で制御
- 軽量な初期化処理
"""

# ------------------------------------------------------------------
# 1. 初期化コード（import 時に 1 度だけ実行される）
# ------------------------------------------------------------------
# main.py からは「初回だけ」このメッセージが出ることを観察できる。
# 重い初期化（DB 接続など）をここに書くと import が遅くなるので注意。
print("[mypkg] __init__.py が実行されました")


# ------------------------------------------------------------------
# 2. パッケージのメタ情報
# ------------------------------------------------------------------
# `mypkg.__version__` のようにフラットにアクセスできるようにしておくのが慣例。
# 実プロジェクトでは setup.py / pyproject.toml と同期させることが多い。
__version__ = "0.1.0"


# ------------------------------------------------------------------
# 3. 公開 API の再エクスポート（curation）
# ------------------------------------------------------------------
# 内部モジュール (mypkg.core) で定義したシンボルを、`mypkg` 直下から触れるように引き上げる。
# こうしておくと利用者は実装ファイルの構成を知らなくてよくなる:
#   from mypkg import Greeter, greet         # ← フラットに使える
#   from mypkg.core import Greeter, greet    # ← 直接モジュールから取ることもできる
from .core import Greeter, greet
# 注意: 相対 import (`from .core ...`) は package 内部の慣例。
# package の外から実行されるスクリプトでは使えないが、__init__.py の中では正しい。


# ------------------------------------------------------------------
# 4. `from mypkg import *` 用の公開シンボル一覧
# ------------------------------------------------------------------
# `from mypkg import *` を書かれたときに何を import するかを制御する。
# 書かない場合は「アンダースコアで始まらない属性すべて」が拾われる。
# ここでは Greeter / greet / __version__ だけを公開対象にする。
#
# 注意: __all__ は `from pkg import *` でしか効かない。
#       `from mypkg.helpers import internal_helper` のような直接 import は
#       __all__ に書いていなくても機能する（== 完全な隠蔽はできない）。
__all__ = ["Greeter", "greet", "__version__"]
